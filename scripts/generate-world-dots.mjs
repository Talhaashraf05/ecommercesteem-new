/** Ray-casting point-in-polygon test. */
const inside = (lon, lat, poly) => {
  let hit = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
};

const dots = [];
for (let lat = 90 - STEP / 2; lat > -90; lat -= STEP) {
  for (let lon = -180 + STEP / 2; lon < 180; lon += STEP) {
    if (Object.values(LAND).some((poly) => inside(lon, lat, poly))) dots.push([lon, lat]);
  }
}

const body = dots.map(([lon, lat]) => `[${lon},${lat}]`).join(",");
const out = `// Generated by scripts/generate-world-dots.mjs — do not edit by hand.
// ${dots.length} land points on a ${STEP}° lon/lat grid.

export const WORLD_DOTS: readonly [number, number][] = [${body}];
`;

const target = fileURLToPath(new URL("../src/features/office-map/world-dots.ts", import.meta.url));
writeFileSync(target, out);
